/** النص بحسب الصيغة المختارة، وهل صُرّف الضمير */
export function duaText(d, form = 'm') {
  if (form === 'f' && d.tf) return { t: d.tf, adapted: true };
  if (form === 'p' && d.tp) return { t: d.tp, adapted: true };
  return { t: d.t, adapted: false };
}

